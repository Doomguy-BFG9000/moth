import { readFileSync, writeFileSync, chmodSync } from "node:fs";
import { machineCompiler } from "./moth.js";
const here = (f) => readFileSync(new URL(`./${f}`, import.meta.url), "utf8");
const machine = machineCompiler(here("machine.moth"), here("compiler.moth"));
const target = process.argv[3] ?? (process.platform === "win32" ? "windows" : "linux");
const src = readFileSync(process.argv[2], "utf8");
const files = {};
for (const n of ["server.moth", "sync.moth", "tasks.moth", "collections.moth", "lists.moth"]) files[n] = readFileSync(new URL(`./tools/${n}`, import.meta.url), "utf8");
const out = process.argv[4] ?? (target === "windows" ? "wtest.exe" : "wtest");
writeFileSync(out, machine(src, { target, name: "w.moth", allow: ["--allow-libraries", "--allow-read", "--allow-write"], files }));
if (target === "linux") chmodSync(out, 0o755);
console.log("made", out);
